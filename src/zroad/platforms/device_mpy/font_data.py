def cjk_glyph(index):
    """把第 index 个 CJK 字形读进复用缓冲并返回（32 字节，MSB 在左）。

    返回的是共享缓冲，每次调用覆盖上次内容，调用方必须当场用完，
    不得长期持有引用（draw_cells 逐字绘制，满足该约定）。
    """
    data_file = open_bin()
    data_file.seek(index * CJK_GLYPH_BYTES)
    data_file.readinto(_scratch)
    return _scratch
