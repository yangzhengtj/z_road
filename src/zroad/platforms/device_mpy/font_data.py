def open_bin():
    """提前打开 font.bin（开局建界面之前调用，文件对象落在整齐堆）。"""
    global _bin
    if _bin is None:
        if '/' in __file__:
            directory = __file__.rsplit('/', 1)[0]
        else:
            directory = __file__.rsplit('\\', 1)[0]
        _bin = open(directory + '/font.bin', 'rb')
    return _bin


def cjk_index(code):
    """按整数码点二分查找字形序号；字库中没有返回 -1（零分配）。"""
    lo, hi = 0, CJK_COUNT - 1
    while lo <= hi:
        mid = (lo + hi) >> 1
        j = mid * 2
        value = (CJK_TABLE[j] << 8) | CJK_TABLE[j + 1]
        if value == code:
            return mid
        if value < code:
            lo = mid + 1
        else:
            hi = mid - 1
    return -1


